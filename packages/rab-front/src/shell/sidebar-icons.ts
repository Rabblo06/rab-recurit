let cataloguePromise: Promise<typeof import('./sidebar-icon-catalogue')> | undefined;
export const loadIconCatalogue = () => cataloguePromise ??= import('./sidebar-icon-catalogue');
export const SIDEBAR_ICONS: Record<string, typeof IconBox> = { ...LEGACY_ICONS };
for (const id of Object.keys(ICON_NAMES)) {
  if (SIDEBAR_ICONS[id]) continue;
  const LazyIcon = lazy(() => loadIconCatalogue().then(module => ({ default: module.catalogue[id as keyof typeof module.catalogue] })));
  SIDEBAR_ICONS[id] = ((props: ComponentPropsWithoutRef<typeof IconBox>) => createElement(Suspense, { fallback: createElement('span', { style: { display: 'inline-block', width: props.size ?? 18, height: props.size ?? 18 }, 'aria-hidden': true }) }, createElement(LazyIcon, props))) as typeof IconBox;
}
export type SidebarIcon = string;
export const SIDEBAR_ICON_IDS = Object.keys(ICON_NAMES);
export function matchSidebarIcons(query: string, selected?: string) {
  const search = query.toLowerCase().trim().replace(/[\s-]/g, '');
  const score = (value: string) => value === search ? 100 : value.startsWith(search) ? 75 : value.includes(search) ? 50 : 0;
  return SIDEBAR_ICON_IDS.map(id => ({ id, score: Math.max(score(id.replaceAll('-', '')), score(ICON_NAMES[id].slice(4).toLowerCase()), search.startsWith('icon') ? score(ICON_NAMES[id].toLowerCase()) : 0) }))
    .filter(item => item.score > 0).sort((a,b) => a.id === selected ? -1 : b.id === selected ? 1 : b.score-a.score).map(item => item.id);
}
