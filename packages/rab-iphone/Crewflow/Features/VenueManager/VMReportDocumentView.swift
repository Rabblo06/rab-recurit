import SwiftUI

/// "Time-sheet" (Flutter `ReportDocumentScreen`): the shift attendance sheet
/// (before/during the shift, with the Shift QR) or the final timesheet
/// (after finalisation), exactly as the server's `actions.document` says.
/// Bytes come from the authorised download (`/files/:id/download`, storage
/// redirect followed without the bearer by the core client) and are checked
/// for `%PDF-`. The file leaves the app only through an explicit share.
/// Delivery state is the server's `deliveryState`, never the finalise reply.
struct VMReportDocumentView: View {
    let shiftId: String
    /// Open the earlier shift attendance sheet even when a final one exists.
    let preShift: Bool

    @EnvironmentObject private var store: VenueManagerStore
    @EnvironmentObject private var environment: AppEnvironment
    @EnvironmentObject private var toasts: ToastCenter
    @State private var report: ShiftReportDetail?
    @State private var document: ReportDocument?
    @State private var file: DownloadedFile?
    @State private var error: String?
    @State private var loading = true
    @State private var shareURL: VMSheetItem<URL>?
    @State private var openPreShift: Bool?

    private static let notPDF = "The stored file is not a valid PDF."

    private var isFinal: Bool { document?.isFinal ?? false }

    var body: some View {
        VMPage(title: isFinal ? "Final timesheet" : "Shift attendance sheet", background: VMColor.reportPage) {
            VStack(alignment: .leading, spacing: 10) {
                HStack {
                    Text(isFinal ? "After shift · recorded hours and feedback" : "Before shift · QR clock-in / out included")
                        .scheduleType(ScheduleType.secondary)
                        .frame(maxWidth: .infinity, alignment: .leading)
                    if isFinal, let lifecycle = report?.lifecycle {
                        let badge = deliveryBadge(lifecycle.deliveryState)
                        ReportBadge(badge.label, tone: badge.tone, systemImage: badge.systemImage)
                            .accessibilityIdentifier("vm.document.delivery")
                    }
                }
                .padding(.horizontal, 20)
                content
            }
        }
        .safeAreaInset(edge: .bottom) {
            VStack {
                if error != nil || (!loading && file == nil) {
                    ReportButton(title: "Retry") { Task { await load() } }
                } else {
                    ReportButton(title: "Download PDF", enabled: file != nil) { share() }
                        .accessibilityIdentifier("vm.document.download")
                }
            }
            .padding(EdgeInsets(top: 12, leading: 20, bottom: 12, trailing: 20))
            .background(VMColor.reportPage.opacity(0.97).ignoresSafeArea())
        }
        .task { await load() }
        .sheet(item: $shareURL) { item in
            VMShareSheet(items: [item.value]) { _ in }
        }
        .vmDestination($openPreShift) { _ in VMReportDocumentView(shiftId: shiftId, preShift: true) }
        .accessibilityIdentifier("vm.document")
    }

    @ViewBuilder
    private var content: some View {
        if loading {
            VMInlineLoading(label: "Loading document")
            Spacer()
        } else if let error {
            ReportNotice(title: "Document unavailable", message: error).padding(20)
            Spacer()
        } else if let file, document != nil {
            if report?.actions?.finalDocumentPending == true && !preShift {
                ReportNotice(title: deliveryBadge(report?.lifecycle?.deliveryState ?? "generating").label,
                             message: "The final timesheet is being prepared. This is the earlier shift attendance sheet.")
                    .padding(.horizontal, 20)
            }
            VMPDFView(data: file.data)
                .clipShape(RoundedRectangle(cornerRadius: 16, style: .continuous))
                .padding(.horizontal, 20)
                .accessibilityLabel(isFinal ? "Final timesheet PDF" : "Shift attendance sheet PDF")
            Text("Pinch to zoom · Scroll to view pages").scheduleType(ScheduleType.caption).padding(.horizontal, 20)
            ReportCard {
                VStack(alignment: .leading, spacing: 4) {
                    Text(isFinal ? "Attendance, ratings and sign-off" : "Staff profiles and scheduled hours").scheduleType(ScheduleType.bodyStrong)
                    Text(isFinal
                         ? "Staff are populated from this shift's assignments. Missing records stay clearly marked."
                         : "Staff are populated from this shift's assignments. The QR is generated by your system for this shift.")
                        .scheduleType(ScheduleType.caption)
                    if isFinal && report?.actions?.preShiftDocument != nil {
                        Button("View the shift attendance sheet (before shift)") { openPreShift = true }
                            .scheduleType(ScheduleType.bodyStrong)
                            .frame(minHeight: 44)
                    }
                }
            }
            .padding(.horizontal, 20)
        } else {
            ReportNotice(title: "Preparing your time-sheet",
                         message: "The attendance sheet is generated automatically before the shift. Check again in a moment.")
                .padding(20)
            Spacer()
        }
    }

    @MainActor
    private func load() async {
        loading = true
        error = nil
        do {
            let fresh = try await store.report(for: shiftId)
            let doc = preShift ? fresh.actions?.preShiftDocument : fresh.actions?.document
            var downloaded: DownloadedFile?
            if let doc {
                let candidate = try await store.repository.downloadDocument(doc.fileId)
                guard candidate.isPDF else {
                    report = fresh
                    error = Self.notPDF
                    loading = false
                    return
                }
                downloaded = candidate
            }
            report = fresh
            document = doc
            file = downloaded
        } catch {
            let api = error as? APIError
            if api != .cancelled, api != .sessionChanged {
                self.error = api?.statusCode == 404
                    ? "The PDF could not be found in storage. It may still be generating, or it needs to be regenerated."
                    : vmMessage(error, fallback: "The document could not be loaded. Check your connection and try again.")
            }
        }
        loading = false
    }

    /// Explicit share only; written to the per-session temp folder (purged
    /// on sign-out). Failure is an error toast; no success toast.
    private func share() {
        guard let file, let document else { return }
        let base = (file.filename ?? document.filename).replacingOccurrences(of: #"[^A-Za-z0-9._-]"#, with: "_", options: .regularExpression)
        let name = base.lowercased().hasSuffix(".pdf") ? base : base + ".pdf"
        do {
            shareURL = VMSheetItem(value: try environment.temporaryFiles.write(file.data, named: name))
        } catch {
            toasts.show("The PDF could not be saved. Tap Download PDF to try again.", kind: .error)
        }
    }
}
