#!/usr/bin/env node
'use strict';
/**
 * Prints a READ-ONLY SQL inventory of a database's migration ledger against the migrations THIS checkout ships
 * (packages/rab-server/src/database/typeorm/core/migrations), so the pending list for a target is computed from the
 * database, never assumed. Used by docs/release/MIGRATION-AND-ROLLBACK-PLAN.md §3.
 *
 *   node packages/rab-docker/staging/print-ledger-inventory-sql.cjs > ledger-inventory.sql
 *   PGOPTIONS='-c default_transaction_read_only=on' psql "<url from the secret store>" -X -v ON_ERROR_STOP=1 \
 *     -P pager=off -f ledger-inventory.sql
 *
 * RUNNING IT AGAINST ANY REAL DATABASE (the temporary OpenShip/Neon one included) IS A SEPARATE OWNER APPROVAL.
 *
 * Guards: the session is read-only three times over (PGOPTIONS, SET SESSION, and BEGIN READ ONLY around every query, so a
 * write fails with SQLSTATE 25006); every query has SET LOCAL statement_timeout / lock_timeout. It reads only
 * core.migrations, pg_roles and pg_auth_members, prints names/timestamps/counts and role ATTRIBUTES only (no password,
 * no URL, no row data), creates nothing (no TEMP table).
 *
 * Output kinds per migration name:
 *   applied              in the ledger and in this code
 *   pending_le_marker    in this code, timestamp <= PRODUCTION_APPROVED_THROUGH, NOT applied (the database is behind the
 *                        reviewed baseline: case L2 of the Phase B production procedure)
 *   pending_after_marker in this code, after the marker, NOT applied (the N1 approval backlog)
 *   unknown              applied but NOT in this code (retired / foreign / newer release: every process refuses it)
 *   gated_applied        a gated migration (core/gated-migrations) found in the ledger — must never happen
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '../../rab-server/src/database/typeorm/core');
const MARKER = 1786719300000; // production-migration-approval.ts PRODUCTION_APPROVED_THROUGH (asserted below)

/** Migration class names (`<Name><13-digit timestamp>`) from `<timestamp>-<Name>.ts` files. */
function migrationNames(dir) {
  return fs.readdirSync(dir).filter((f) => /^\d{13}-[A-Za-z0-9]+\.ts$/.test(f) && !f.endsWith('.spec.ts')).sort()
    .map((f) => {
      const [, ts, name] = /^(\d{13})-([A-Za-z0-9]+)\.ts$/.exec(f);
      const src = fs.readFileSync(path.join(dir, f), 'utf8');
      const declared = (/export class ([A-Za-z0-9]+)\s+implements\s+MigrationInterface/.exec(src) || [])[1];
      const cls = declared ?? `${name}${ts}`;
      if (!cls.endsWith(ts)) throw new Error(`${f}: class name ${cls} does not end with its timestamp`);
      return { ts: Number(ts), name: cls };
    });
}

function inventorySql() {
  const approval = fs.readFileSync(path.join(ROOT, 'production-migration-approval.ts'), 'utf8');
  const through = Number((/PRODUCTION_APPROVED_THROUGH\s*=\s*(\d{13})/.exec(approval) || [])[1]);
  if (through !== MARKER) throw new Error(`PRODUCTION_APPROVED_THROUGH is ${through}, this script expects ${MARKER}; review the plan first`);
  const code = migrationNames(path.join(ROOT, 'migrations'));
  // Gated migrations move into core/migrations/ on approval, so the directory may be empty or absent (git keeps no empty dir).
  const gatedDir = path.join(ROOT, 'gated-migrations');
  const gated = fs.existsSync(gatedDir) ? migrationNames(gatedDir) : [];
  const values = (rows) => rows.map((r) => `  ('${r.name}', ${r.ts})`).join(',\n');
  // A typed empty relation when there is no row (a VALUES list with no row is a syntax error).
  const relation = (rows) => (rows.length ? `VALUES\n${values(rows)}` : 'SELECT NULL::varchar, NULL::bigint WHERE false');
  const head = `-- Crewflow migration-ledger inventory (READ ONLY). Generated by packages/rab-docker/staging/print-ledger-inventory-sql.cjs
-- from ${code.length} shipped migrations (max ${code[code.length - 1].ts}) and ${gated.length} gated one(s); marker ${MARKER}.
-- Running it against a real database needs its own owner approval. It writes nothing.
\\set ON_ERROR_STOP 1
\\pset pager off
SET SESSION default_transaction_read_only = on;
`;
  const q = (title, sql) => `\n\\echo '=== ${title} ==='\nBEGIN READ ONLY;\nSET LOCAL statement_timeout = '30s';\nSET LOCAL lock_timeout = '2s';\n${sql}\nROLLBACK;\n`;
  const ledgerCte = `WITH code(name, ts) AS (VALUES\n${values(code)}\n), gated(name, ts) AS (${relation(gated)}\n), ledger AS (\n  SELECT name, timestamp AS ts FROM core.migrations\n), classified AS (\n  SELECT c.name, c.ts, CASE WHEN l.name IS NOT NULL THEN 'applied' WHEN c.ts <= ${MARKER} THEN 'pending_le_marker' ELSE 'pending_after_marker' END AS kind\n    FROM code c LEFT JOIN ledger l ON l.name = c.name\n  UNION ALL\n  SELECT l.name, l.ts, CASE WHEN g.name IS NOT NULL THEN 'gated_applied' ELSE 'unknown' END\n    FROM ledger l LEFT JOIN code c ON c.name = l.name LEFT JOIN gated g ON g.name = l.name WHERE c.name IS NULL\n)`;
  return head
    + q('L0. session (must show read_only on) and the inventory login\'s attributes', `SELECT current_setting('transaction_read_only') AS transaction_read_only, current_database() AS database, current_user AS login,\n       r.rolsuper, r.rolbypassrls, current_setting('server_version') AS server_version, now() AS observed_at\n  FROM pg_roles r WHERE r.rolname = current_user;\n-- rolbypassrls = false is fine here: core.migrations has no RLS. The role checks below read catalogs only.`)
    + `\nSELECT to_regclass('core.migrations') IS NOT NULL AS has_ledger \\gset\n\\if :has_ledger`
    + q('L1. ledger summary by kind', `${ledgerCte}\nSELECT kind, count(*) AS migrations, min(ts) AS first_ts, max(ts) AS last_ts FROM classified GROUP BY kind ORDER BY kind;`)
    + q('L2. every pending, unknown or gated name, in run order', `${ledgerCte}\nSELECT kind, ts, name FROM classified WHERE kind <> 'applied' ORDER BY ts, name;`)
    + q('L3. applied after the marker (exact names)', `SELECT timestamp, name FROM core.migrations WHERE timestamp > ${MARKER} ORDER BY timestamp;`)
    + `\n\\else\n\\echo 'core.migrations does not exist: an empty database (fresh install: every shipped migration is pending)'\n\\endif\n`
    + q('L4. database roles the release depends on (attributes only)', `SELECT rolname, rolcanlogin, rolsuper, rolbypassrls, rolcreaterole, rolcreatedb, rolreplication, rolinherit,\n       (SELECT count(*) FROM pg_auth_members m WHERE m.member = r.oid) AS member_of_count\n  FROM pg_roles r\n WHERE rolname IN ('rab_owner', 'rab_app', 'crewflow', 'crewflow_app', 'crewflow_worker', 'crewflow_migrator', 'rab_secure_owner')\n ORDER BY rolname;`)
    + q('L5. crewflow_worker shape (Phase D precondition; expected t f f f f f t | crewflow_app:inherit=true:set=false:admin=false | 0 | 0)', `SELECT r.rolcanlogin, r.rolsuper, r.rolbypassrls, r.rolcreaterole, r.rolcreatedb, r.rolreplication, r.rolinherit,\n       (SELECT string_agg(g.rolname || ':inherit=' || m.inherit_option || ':set=' || m.set_option || ':admin=' || m.admin_option, ',')\n          FROM pg_auth_members m JOIN pg_roles g ON g.oid = m.roleid WHERE m.member = r.oid) AS member_of,\n       (SELECT count(*) FROM pg_auth_members m WHERE m.roleid = r.oid) AS members,\n       (SELECT count(*) FROM pg_shdepend d WHERE d.refobjid = r.oid AND d.deptype = 'o') AS owns\n  FROM pg_roles r WHERE r.rolname = 'crewflow_worker';\n-- No row = the role does not exist yet (PostgreSQL < 16 lacks inherit_option/set_option: the query then fails, read-only).`);
}

if (require.main === module) process.stdout.write(inventorySql());

module.exports = { inventorySql, migrationNames, MARKER };
