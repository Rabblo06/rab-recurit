/**
 * Twenty Mode Option A, owner decision D4 (2026-11-04): catalog renderings differ between PostgreSQL major versions (PG18
 * adds `contype = 'n'` NOT NULL constraint rows, M0 finding B4), so a workspace fingerprint is only meaningful against the
 * values generated on the SAME major. PostgreSQL 16 keeps the values above, unchanged; PostgreSQL 18 has its own set
 * (expected-fingerprints-pg18.ts). Every other major is unsupported.
 *
 * `EXPECTED_WORKSPACE_FINGERPRINTS` (below) is what every caller reads: the frozen migrations, the TypeScript provisioner,
 * the migrator and the drift job. It is a read-only view of the table selected for this process's database server:
 *   - nothing selected (every existing process that never calls the selector): the PostgreSQL 16 table, exactly as
 *     before, so separated mode on PostgreSQL 16 is unchanged byte for byte;
 *   - selectWorkspaceFingerprintsForServer(...) with 16 or 18: that major's table. A process talks to ONE server, so a
 *     second selection with a different major is refused (never a silent switch).
 * The frozen migrations read the view inside up() (never at import), so a migration run selected for PostgreSQL 18 bakes
 * the PostgreSQL 18 literal into core.provision_workspace(uuid), and the TypeScript provisioner compares against the same
 * major. A wrong selection fails closed: the fingerprint comparison refuses (FINGERPRINT_MISMATCH), it never passes.
 */
export const SUPPORTED_FINGERPRINT_MAJORS = [16, 18] as const;
export type FingerprintMajor = (typeof SUPPORTED_FINGERPRINT_MAJORS)[number];
/** Below this, Twenty Mode refuses the server outright (M0 F-E1: CREATEROLE can grant pg_execute_server_program on <= 15). */
export const MINIMUM_POSTGRES_MAJOR = 16;

const TABLES: Readonly<Record<FingerprintMajor, Readonly<Record<number, string>>>> = {
  16: EXPECTED_WORKSPACE_FINGERPRINTS_PG16,
  18: EXPECTED_WORKSPACE_FINGERPRINTS_PG18,
};

export class UnsupportedPostgresVersionError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'UnsupportedPostgresVersionError';
  }
}

let selected: FingerprintMajor | null = null;

/** The major whose table the view serves (16 when nothing was selected). */
export function workspaceFingerprintMajor(): FingerprintMajor {
  return selected ?? 16;
}

/** True once a process selected a major explicitly. */
export function workspaceFingerprintMajorSelected(): boolean {
  return selected !== null;
}

/** `server_version_num` (e.g. 160015, 180006) to the major version. Throws on anything else. */
export function postgresMajorOf(serverVersionNum: string | number): number {
  const n = typeof serverVersionNum === 'number' ? serverVersionNum : Number(String(serverVersionNum).trim());
  if (!Number.isInteger(n) || n < 100000 || n > 9990000) {
    throw new UnsupportedPostgresVersionError('server_version_num is not a PostgreSQL 10+ version number. Refusing.');
  }
  return Math.floor(n / 10000);
}

/**
 * Pure decision for a server major:
 *   below MINIMUM_POSTGRES_MAJOR  refused (UnsupportedPostgresVersionError);
 *   16 or 18                      that major;
 *   anything else                 refused: no reviewed fingerprints exist for it (generate and commit them first).
 */
export function assertSupportedPostgresMajor(major: number): FingerprintMajor {
  if (major < MINIMUM_POSTGRES_MAJOR) {
    throw new UnsupportedPostgresVersionError(
      `PostgreSQL ${major} is refused: Crewflow needs PostgreSQL ${MINIMUM_POSTGRES_MAJOR} or later (on 15 and earlier a CREATEROLE login can grant ` +
        'predefined roles such as pg_execute_server_program).',
    );
  }
  if (!(SUPPORTED_FINGERPRINT_MAJORS as readonly number[]).includes(major)) {
    throw new UnsupportedPostgresVersionError(
      `PostgreSQL ${major} is not supported: workspace fingerprints are generated for ${SUPPORTED_FINGERPRINT_MAJORS.join(' and ')} only ` +
        '(workspace-schema/v1/expected-fingerprints*.ts). Generate and review them on that major first.',
    );
  }
  return major as FingerprintMajor;
}

/** Selects the table for `major` (validated by assertSupportedPostgresMajor). Idempotent; a different second major throws. */
export function selectWorkspaceFingerprintMajor(major: number): FingerprintMajor {
  const m = assertSupportedPostgresMajor(major);
  if (selected !== null && selected !== m) {
    throw new UnsupportedPostgresVersionError(`workspace fingerprints were selected for PostgreSQL ${selected}; this process cannot switch to ${m}.`);
  }
  selected = m;
  return m;
}

/** Reads `server_version_num` on the caller's session and selects that major. */
export async function selectWorkspaceFingerprintsForServer(
  query: (sql: string) => Promise<Array<Record<string, unknown>>>,
): Promise<FingerprintMajor> {
  const [row] = await query(`SELECT pg_catalog.current_setting('server_version_num') AS "num"`);
  return selectWorkspaceFingerprintMajor(postgresMajorOf(String(row?.num ?? '')));
}

/** Test seam only: forget the selection (unit specs that exercise both majors in one process). */
export function resetWorkspaceFingerprintSelectionForTests(): void {
  selected = null;
}

function selectedView(): Readonly<Record<number, string>> {
  const view: Record<number, string> = {};
  const versions = new Set<number>();
  for (const table of Object.values(TABLES)) for (const v of Object.keys(table)) versions.add(Number(v));
  for (const v of [...versions].sort((a, b) => a - b)) {
    Object.defineProperty(view, v, { enumerable: true, get: () => TABLES[workspaceFingerprintMajor()][v] });
  }
  return Object.freeze(view);
}

/**
 * The expected fingerprint per module version for the selected PostgreSQL major (PG16 unless selected otherwise). A
 * version without a value on the selected major reads `undefined`, exactly like a version that does not exist.
 */
export const EXPECTED_WORKSPACE_FINGERPRINTS: Readonly<Record<number, string>> = selectedView();
