const THROUGH_VERSION = 20;
const PREVIOUS_VERSION = 19;
const PREVIOUS_APP_VERSION = 'db:provision_workspace@StatementDispatchPointer1786721320000';

/**
 * PAY-1, workspace copies (owner-login architecture): workspace module v1.020 attaches the grant-parity guards of
 * OwnerLoginGrantParityGuards1786721420000 to the workspace-schema copies of payroll_record, payroll_run,
 * payroll_run_line, payslip, payslip_document (UPDATE allow-list / DELETE / TRUNCATE) and shift_staff_review (DELETE).
 * Frozen SQL and reasoning: ../../workspace-schema/v1/grant-parity-guards.ts. Same pattern as StatementDispatchPointer1786721320000:
 *  1. in ONE transaction: the literal allow-lists are re-checked against crewflow_app's live column privileges on the core
 *     counterparts (refuse on any difference); core.provision_workspace is re-created (guarded v3 body) over the v20
 *     composition with the v20 expected fingerprint; privilege shape and secure-owner invariants re-verified;
 *  2. every READY workspace migrated to module 20 by WorkspaceSchemaMigrator (one transaction per schema; it takes SET
 *     LOCAL ROLE crewflow itself, M-T2); a failing schema is rolled back and recorded; the migration then throws and a
 *     re-run resumes.
 * Refuses while the v20 expected fingerprint is pending (v1/expected-fingerprints.ts PENDING_FINGERPRINT_VERSIONS; it is
 * generated by Agent 1's append mode on disposable PG16 and PG18 after this SQL is reviewed).
 * MIN_COMPATIBLE_WORKSPACE_MODULE_VERSION stays 18: module 20 adds triggers only, which this code never depends on.
 * down(): restores the 1786721320000 provision_workspace body (module 19); workspace schemas keep module 20 (append-only
 * ledger), their guards stay (they only refuse what crewflow_app could never do).
 */
export class WorkspaceGrantParityGuards1786721430000 implements MigrationInterface {
  name = 'WorkspaceGrantParityGuards1786721430000';
  transaction = false;

  public async up(queryRunner: QueryRunner): Promise<void> {
    const expected = EXPECTED_WORKSPACE_FINGERPRINTS[THROUGH_VERSION];
    if (!expected) {
      throw new Error(`${this.name}: no expected fingerprint for module version ${THROUGH_VERSION} (pending; see v1/expected-fingerprints.ts PENDING_FINGERPRINT_VERSIONS)`);
    }
    const outer = queryRunner.isTransactionActive;
    if (!outer) await queryRunner.query('BEGIN');
    try {
      await pinSearchPath(queryRunner);
      await this.preflight(queryRunner);
      await this.verifyAllowLists(queryRunner);
      const modules = modulesThrough(THROUGH_VERSION).map((m) => ({ id: m.id, version: m.version, checksum: moduleChecksum(m) }));
      await queryRunner.query(provisionWorkspaceFunctionV3Sql(composeServerPathTemplateV1GrantParity(), modules, expected, `db:provision_workspace@${this.name}`));
      await this.verifyProvisionFunction(queryRunner, `db:provision_workspace@${this.name}`);
      const violations = await secureOwnerInvariantViolations((sql) => queryRunner.query(sql));
      if (violations.length) throw new Error(`${this.name}: secure-owner invariants violated (rolled back):\n  ${violations.join('\n  ')}`);
      if (!outer) await queryRunner.query('COMMIT');
    } catch (error) {
      if (!outer) await queryRunner.query('ROLLBACK');
      throw error;
    }

    const outcomes = await new WorkspaceSchemaMigrator(queryRunner).migrateAll({
      throughVersion: THROUGH_VERSION,
      txMode: outer ? 'savepoint' : 'own',
      appVersion: `migration:${this.name}`,
      lockTimeoutMs: Number.parseInt(DISPATCH_TRIGGER_LOCK_TIMEOUT, 10) * 1000,
    });
    const bad = outcomes.filter((o) => o.status === 'FAILED' || o.status === 'REFUSED');
    // eslint-disable-next-line no-console
    console.log(
      `[${this.name}] workspaces: ${outcomes.filter((o) => o.status === 'MIGRATED').length} migrated, ` +
        `${outcomes.filter((o) => o.status === 'UP_TO_DATE' || o.status === 'BASELINED').length} already current, ` +
        `${outcomes.filter((o) => o.status === 'SKIPPED').length} skipped (not READY), ${bad.length} failed/refused`,
    );
    if (bad.length) {
      throw new Error(
        `${this.name}: ${bad.length} workspace schema(s) did not reach module ${THROUGH_VERSION}: ` +
          bad.map((o) => `${o.schemaName} ${o.status} ${o.errorClass} at ${o.moduleId}`).join('; ') +
          '. Each is rolled back and recorded in core.workspace_schema_migration; fix and re-run (resumes).',
      );
    }
  }

  public async down(queryRunner: QueryRunner): Promise<void> {
    const outer = queryRunner.isTransactionActive;
    if (!outer) await queryRunner.query('BEGIN');
    try {
      await pinSearchPath(queryRunner);
      await this.preflight(queryRunner);
      const previous = EXPECTED_WORKSPACE_FINGERPRINTS[PREVIOUS_VERSION];
      if (!previous) throw new Error(`${this.name}: no expected fingerprint for module version ${PREVIOUS_VERSION}`);
      const modules = modulesThrough(PREVIOUS_VERSION).map((m) => ({ id: m.id, version: m.version, checksum: moduleChecksum(m) }));
      await queryRunner.query(provisionWorkspaceFunctionV3Sql(composeServerPathTemplateV1StatementPointer(), modules, previous, PREVIOUS_APP_VERSION));
      await this.verifyProvisionFunction(queryRunner, PREVIOUS_APP_VERSION);
      if (!outer) await queryRunner.query('COMMIT');
    } catch (error) {
      if (!outer) await queryRunner.query('ROLLBACK');
      throw error;
    }
  }

  private async preflight(queryRunner: QueryRunner): Promise<void> {
    const [f] = (await queryRunner.query(BOOTSTRAP_IDENTITY_SQL)) as BootstrapIdentityFacts[];
    const problems = bootstrapIdentityProblems(f);
    const [g] = (await queryRunner.query(
      `SELECT pg_catalog.to_regprocedure('core.owner_login_grant_parity_guard()') IS NOT NULL AS present`,
    )) as Array<{ present: boolean }>;
    if (!g?.present) problems.push('core.owner_login_grant_parity_guard() does not exist (OwnerLoginGrantParityGuards1786721420000 first)');
    if (problems.length) throw new Error(`${this.name}: refusing to run as ${f?.who ?? 'unknown'}: ${problems.join('; ')}.`);
  }

  /** The frozen allow-lists equal crewflow_app's live UPDATE column privileges (and it has no DELETE) on the core tables. */
  private async verifyAllowLists(queryRunner: QueryRunner): Promise<void> {
    const tables = [...Object.keys(WORKSPACE_PARITY_UPDATABLE), ...WORKSPACE_PARITY_DELETE_ONLY];
    const rows = (await queryRunner.query(
      `SELECT c.relname::text AS tbl,
              coalesce((SELECT pg_catalog.array_agg(a.attname::text ORDER BY a.attname) FROM pg_catalog.pg_attribute a
                         WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
                           AND pg_catalog.has_column_privilege('crewflow_app', c.oid, a.attnum, 'UPDATE')), ARRAY[]::text[]) AS updatable,
              pg_catalog.has_table_privilege('crewflow_app', c.oid, 'DELETE') AS app_delete,
              pg_catalog.has_table_privilege('crewflow_app', c.oid, 'TRUNCATE') AS app_truncate
         FROM pg_catalog.pg_class c WHERE c.relnamespace = 'core'::regnamespace AND c.relname = ANY ($1::text[])`,
      [tables],
    )) as Array<{ tbl: string; updatable: string[]; app_delete: boolean; app_truncate: boolean }>;
    const problems: string[] = [];
    for (const [table, list] of Object.entries(WORKSPACE_PARITY_UPDATABLE)) {
      const r = rows.find((x) => x.tbl === table);
      const want = [...list].sort().join(',');
      if (!r) problems.push(`core.${table} missing`);
      else if (r.updatable.join(',') !== want || r.app_delete || r.app_truncate) {
        problems.push(`core.${table}: crewflow_app may update [${r.updatable.join(',')}] delete=${r.app_delete} truncate=${r.app_truncate}; frozen allow-list [${want}]`);
      }
    }
    for (const table of WORKSPACE_PARITY_DELETE_ONLY) {
      const r = rows.find((x) => x.tbl === table);
      if (!r || r.app_delete) problems.push(`core.${table}: crewflow_app delete=${String(r?.app_delete)} (expected false)`);
    }
    if (problems.length) throw new Error(`${this.name}: the frozen workspace allow-lists no longer match crewflow_app's grants (nothing changed):\n  ${problems.join('\n  ')}`);
  }

  private async verifyProvisionFunction(queryRunner: QueryRunner, appVersion: string): Promise<void> {
    const [p] = (await queryRunner.query(PROVISION_WORKSPACE_STATE_SQL)) as Array<Record<string, unknown>>;
    const shapeOk = Object.entries(PROVISION_WORKSPACE_PRIVILEGE_SHAPE).every(([k, v]) => p?.[k] === v);
    const [body] = (await queryRunner.query(
      `SELECT pg_catalog.strpos(p.prosrc, $1) > 0 AS ours FROM pg_catalog.pg_proc p WHERE p.oid = 'core.provision_workspace(uuid)'::pg_catalog.regprocedure`,
      [appVersion],
    )) as Array<{ ours: boolean }>;
    if (!shapeOk || p?.has_guards !== true || body?.ours !== true) {
      throw new Error(`${this.name}: core.provision_workspace lost its privilege shape or body: ${JSON.stringify(p)}`);
    }
  }
}

/** Same as Phase 0b: this session resolves names in pg_catalog only; every object named here is core-qualified. */
async function pinSearchPath(queryRunner: QueryRunner): Promise<void> {
  await queryRunner.query(`SELECT pg_catalog.set_config('search_path', 'pg_catalog, pg_temp', true)`);
}
