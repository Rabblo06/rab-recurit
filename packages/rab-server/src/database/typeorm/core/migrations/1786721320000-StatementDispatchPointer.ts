const THROUGH_VERSION = 19;

/**
 * Phase D / D1: Approved Shift Statement dispatch pointers (core + every workspace schema). SQL owner-approved 2026-11-01 (docs/plans/PHASE-D-SQL-GATE.md),
 * normal execution after the v19 fingerprint sign-off (docs/plans/PHASE-D-V19-FINGERPRINT.md); exact SQL in
 * ../worker-dispatch-pointer-sql.ts and ../../workspace-schema/v1/statement-dispatch-pointer.ts. Executed on disposable
 * test databases only. Not in production-migration-approval.ts.
 *
 * Pattern: VenueTeamOrgAdmin1786721090000 (module list is the single source of truth; WorkspaceSchemaMigrator).
 *  1. (one transaction) `core.worker_dispatch_pointer_statement_trg()` (SECURITY DEFINER, rab_secure_owner,
 *     `search_path = pg_catalog, pg_temp`; EXECUTE crewflow only — SECURITY TRADE-OFF below); module v1.019 applied to
 *     `core.payroll_record` (three AFTER ROW + one AFTER TRUNCATE trigger, E-4) after `SET LOCAL lock_timeout = '5s'`
 *     (E-8: DROP TRIGGER IF EXISTS takes ACCESS EXCLUSIVE; fail fast, retry = re-run); `core.provision_workspace(uuid)` re-created as the guarded v3 body
 *     (ProvisionWorkspaceGuards1786721210000) over the v19 composition with the v19 expected fingerprint; privilege shapes
 *     and secure-owner invariants re-verified.
 *  2. Every READY workspace migrated to module 19 by WorkspaceSchemaMigrator (one transaction per schema, ledger rows,
 *     fingerprint must equal the frozen v19 value). A failing schema is rolled back and recorded; the migration then throws
 *     (not recorded as applied) and a re-run resumes (step 1 is idempotent: CREATE OR REPLACE, DROP TRIGGER IF EXISTS).
 *  Workspaces still at 18 stay routable (MIN_COMPATIBLE_WORKSPACE_MODULE_VERSION = 18); their statements are dispatched by
 *  the per-workspace reconciliation cycle until they reach 19.
 *
 * Refuses to run while the v19 expected fingerprint is pending (it can only be generated by executing this SQL on a
 * disposable database after approval — v1/expected-fingerprints.ts PENDING_FINGERPRINT_VERSIONS; the M2 harness also
 * refuses a release while that list is non-empty, E-10). The final fingerprint literal is re-shown to the owner for
 * sign-off. MIN_COMPATIBLE_WORKSPACE_MODULE_VERSION = 18 is temporary: reset it to LATEST with the next module (spec).
 *
 * SECURITY TRADE-OFF: crewflow holds EXECUTE on core.worker_dispatch_pointer_statement_trg(), because PostgreSQL checks
 * EXECUTE for the role that runs CREATE TRIGGER, and new workspace schemas are built by crewflow (core.provision_workspace,
 * a crewflow-owned DEFINER, and the TypeScript provisioner child). The narrower alternative — a rab_secure_owner function
 * that attaches the trigger for a registry-resolved workspace — needs dynamic SQL in a rab_secure_owner definer and names
 * the crewflow-owned payroll table in its body (both Phase 0b frozen lists would grow) plus a TRIGGER grant to
 * rab_secure_owner on every payroll table, and would not reduce what crewflow can do: as owner of every payroll table it
 * can already make this function write any statement pointer by writing rows. The function confines itself instead: it
 * refuses on any table not named `payroll_record` (E-2, preventive), in any schema not owned by rab_secure_owner (N-2:
 * crewflow has CREATE on the database and could create `workspace_<unprovisioned id>` itself, but would own it), outside
 * AFTER ROW / AFTER TRUNCATE STATEMENT, outside
 * `core` or the workspace's own schema, on columns of an unreviewed type, on a workspace that is not the organisation's,
 * and on a change of the source row's scope; secure-owner-invariants.ts reports (detective) any attachment outside
 * `core.payroll_record` / `workspace_<hex>.payroll_record`. A forged pointer is a wasted Worker visit: the Worker re-reads
 * the record under the pointer's own organisation and workspace (RLS) and finds nothing. Full analysis: docs/plans/PHASE-D-SQL-GATE.md.
 *
 * down(): restores the 1786721210000 provision_workspace body (module 18) and replaces the trigger function with an inert
 * body (RETURN NULL), keeping its owner and ACL. Workspace schemas keep module 19 (the ledger is append-only history, as in
 * 1786721090000's down()); their triggers then do nothing and never reference the pointer table, so 1786721300000's down()
 * can drop it safely. `transaction = false` for the per-schema transactions.
 */
export class StatementDispatchPointer1786721320000 implements MigrationInterface {
  name = 'StatementDispatchPointer1786721320000';
  transaction = false;

  public async up(queryRunner: QueryRunner): Promise<void> {
    const expected = EXPECTED_WORKSPACE_FINGERPRINTS[THROUGH_VERSION];
    if (!expected) {
      throw new Error(
        `${this.name}: no expected fingerprint for module version ${THROUGH_VERSION} (pending until the owner approves the SQL; see v1/expected-fingerprints.ts)`,
      );
    }
    const outer = queryRunner.isTransactionActive;

    if (!outer) await queryRunner.query('BEGIN');
    try {
      await pinSearchPath(queryRunner);
      await this.preflight(queryRunner);
      // E-8: DROP TRIGGER IF EXISTS takes ACCESS EXCLUSIVE on core.payroll_record — fail fast behind a long transaction.
      await queryRunner.query(LOCK_TIMEOUT_SQL);
      for (const sql of STATEMENT_TRIGGER_FUNCTION_UP_SQL) await queryRunner.query(sql);
      await queryRunner.query(statementDispatchPointerSql('core'));
      const modules = modulesThrough(THROUGH_VERSION).map((m) => ({ id: m.id, version: m.version, checksum: moduleChecksum(m) }));
      await queryRunner.query(provisionWorkspaceFunctionV3Sql(composeServerPathTemplateV1StatementPointer(), modules, expected, `db:provision_workspace@${this.name}`));
      await this.verifyFunctions(queryRunner, 'up');
      await this.verifyCoreTriggers(queryRunner);
      const violations = await secureOwnerInvariantViolations((sql) => queryRunner.query(sql));
      if (violations.length) throw new Error(`${this.name}: secure-owner invariants violated (rolled back):\n  ${violations.join('\n  ')}`);
      if (!outer) await queryRunner.query('COMMIT');
    } catch (error) {
      if (!outer) await queryRunner.query('ROLLBACK');
      throw error;
    }

    const outcomes = await new WorkspaceSchemaMigrator(queryRunner).migrateAll({
      throughVersion: THROUGH_VERSION,
      txMode: outer ? 'savepoint' : 'own',
      appVersion: `migration:${this.name}`,
      // E-8: same bound as the core step (DROP TRIGGER IF EXISTS takes ACCESS EXCLUSIVE on each workspace payroll table).
      lockTimeoutMs: Number.parseInt(DISPATCH_TRIGGER_LOCK_TIMEOUT, 10) * 1000,
    });
    const bad = outcomes.filter((o) => o.status === 'FAILED' || o.status === 'REFUSED');
    // eslint-disable-next-line no-console
    console.log(
      `[${this.name}] workspaces: ${outcomes.filter((o) => o.status === 'MIGRATED').length} migrated, ` +
        `${outcomes.filter((o) => o.status === 'UP_TO_DATE' || o.status === 'BASELINED').length} already current, ` +
        `${outcomes.filter((o) => o.status === 'SKIPPED').length} skipped (not READY), ${bad.length} failed/refused`,
    );
    if (bad.length) {
      throw new Error(
        `${this.name}: ${bad.length} workspace schema(s) did not reach module ${THROUGH_VERSION}: ` +
          bad.map((o) => `${o.schemaName} ${o.status} ${o.errorClass} at ${o.moduleId}`).join('; ') +
          '. Each is rolled back and recorded in core.workspace_schema_migration; the others are migrated. Fix and re-run (resumes).',
      );
    }
  }

  public async down(queryRunner: QueryRunner): Promise<void> {
    // `migration:revert` always opens a transaction (TypeORM ignores `transaction = false` on revert): join it.
    const outer = queryRunner.isTransactionActive;
    if (!outer) await queryRunner.query('BEGIN');
    try {
      await pinSearchPath(queryRunner);
      await this.preflight(queryRunner);
      await queryRunner.query(provisionWorkspaceGuardsUpSql());
      await queryRunner.query(STATEMENT_TRIGGER_FUNCTION_INERT_SQL);
      await this.verifyFunctions(queryRunner, 'down');
      if (!outer) await queryRunner.query('COMMIT');
    } catch (error) {
      if (!outer) await queryRunner.query('ROLLBACK');
      throw error;
    }
  }

  private async preflight(queryRunner: QueryRunner): Promise<void> {
    const [f] = (await queryRunner.query(BOOTSTRAP_IDENTITY_SQL)) as BootstrapIdentityFacts[];
    const problems = bootstrapIdentityProblems(f);
    const [t] = (await queryRunner.query(`SELECT pg_catalog.to_regclass('core.worker_dispatch_pointer') IS NOT NULL AS present`)) as Array<{ present: boolean }>;
    if (!t?.present) problems.push('core.worker_dispatch_pointer does not exist (WorkerDispatchPointer1786721300000 first)');
    if (problems.length) throw new Error(`${this.name}: refusing to run as ${f?.who ?? 'unknown'}: ${problems.join('; ')}.`);
  }

  /** provision_workspace keeps its privilege shape and carries the expected body; the trigger function keeps its shape. */
  private async verifyFunctions(queryRunner: QueryRunner, direction: 'up' | 'down'): Promise<void> {
    const [p] = (await queryRunner.query(PROVISION_WORKSPACE_STATE_SQL)) as Array<Record<string, unknown>>;
    const shapeOk = Object.entries(PROVISION_WORKSPACE_PRIVILEGE_SHAPE).every(([k, v]) => p?.[k] === v);
    const [body] = (await queryRunner.query(
      `SELECT pg_catalog.strpos(p.prosrc, $1) > 0 AS ours FROM pg_catalog.pg_proc p WHERE p.oid = 'core.provision_workspace(uuid)'::pg_catalog.regprocedure`,
      [direction === 'up' ? `db:provision_workspace@${this.name}` : 'db:provision_workspace@ProvisionWorkspaceGuards1786721210000'],
    )) as Array<{ ours: boolean }>;
    if (!shapeOk || p?.has_guards !== true || body?.ours !== true) {
      throw new Error(`${this.name}: core.provision_workspace lost its privilege shape or body (${direction}): ${JSON.stringify(p)}`);
    }
    const [s] = (await queryRunner.query(STATEMENT_FUNCTION_STATE_SQL)) as Array<{ fn: string; executors: string }>;
    if (s?.fn !== STATEMENT_FUNCTION_EXPECTED.fn || s?.executors !== STATEMENT_FUNCTION_EXPECTED.executors) {
      throw new Error(`${this.name}: core.worker_dispatch_pointer_statement_trg() has an unexpected shape (${direction}): ${JSON.stringify(s)}`);
    }
  }

  private async verifyCoreTriggers(queryRunner: QueryRunner): Promise<void> {
    const [row] = (await queryRunner.query(
      `SELECT pg_catalog.string_agg(g.tgname || ':' || g.tgfoid::pg_catalog.regprocedure::text || ':' || g.tgenabled::text, ',' ORDER BY g.tgname) AS t
         FROM pg_catalog.pg_trigger g
        WHERE g.tgrelid = 'core.payroll_record'::pg_catalog.regclass AND NOT g.tgisinternal AND g.tgname LIKE 'payroll_record_statement_pointer_%'`,
    )) as Array<{ t: string | null }>;
    const fn = 'core.worker_dispatch_pointer_statement_trg()';
    const expected = ['del', 'ins', 'trunc', 'upd'].map((s) => `payroll_record_statement_pointer_${s}:${fn}:O`).join(',');
    if (row?.t !== expected) throw new Error(`${this.name}: unexpected statement pointer triggers on core.payroll_record: ${row?.t ?? 'none'}`);
  }
}

/** Same as Phase 0b: this session resolves names in pg_catalog only; every object named here is core-qualified. */
async function pinSearchPath(queryRunner: QueryRunner): Promise<void> {
  await queryRunner.query(`SELECT pg_catalog.set_config('search_path', 'pg_catalog, pg_temp', true)`);
}
