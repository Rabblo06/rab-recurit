/**
 * Compares a database's SEMANTIC security posture (policies, function bodies and config, triggers, RLS flags, the audit_log
 * ACL, owners, stored settings — posture-drift/semantic-posture.ts) with the committed golden for its PostgreSQL major.
 *
 *   POSTURE_DATABASE_URL=postgres://... ts-node check-semantic-posture.ts           # exit 1 on any drift
 *   POSTURE_DATABASE_URL=postgres://... ts-node check-semantic-posture.ts --write   # regenerate semantic-golden.pg<major>.ts
 *
 * The URL is read ONLY from POSTURE_DATABASE_URL (never .env / DATABASE_URL); any role that can read the catalog works.
 * Regenerate the golden only from a database built from migrations ALONE with the owner-login bootstrap, on the major it
 * is for, and review the diff like code: every changed line is a policy, function body, trigger or privilege change.
 * NEVER regenerate it from a database you are investigating (that would bless the drift).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { createPgClientForUrl } from '../../postgres';
import { SEMANTIC_GOLDEN_BY_MAJOR } from '../../posture-drift/semantic-golden';
import { describeSemanticDrift, readSemanticPosture, semanticDriftFromGolden, semanticGoldenLines, splitSemanticGolden } from '../../posture-drift/semantic-posture';

async function main(): Promise<void> {
  const url = process.env.POSTURE_DATABASE_URL?.trim();
  if (!url) throw new Error('POSTURE_DATABASE_URL is required. There is no fallback.');
  const client = createPgClientForUrl(url, 'the posture database URL', { purpose: 'posture', statementTimeoutMs: 120_000 });
  await client.connect();
  try {
    const posture = await readSemanticPosture(async (sql, params) => (await client.query(sql, params as unknown[] | undefined)).rows);
    const existing = SEMANTIC_GOLDEN_BY_MAJOR[posture.serverMajor] ?? [];
    if (process.argv.includes('--write')) {
      const lines = semanticGoldenLines(posture, splitSemanticGolden(existing).workspace);
      const file = join(__dirname, '..', '..', 'posture-drift', `semantic-golden.pg${posture.serverMajor}.ts`);
      const body =
        `// GENERATED by check-semantic-posture.ts --write from a migrations-only owner-login database (PostgreSQL ${posture.serverMajor}).\n` +
        `// Review every changed line like code. Never regenerate from a database under investigation.\n` +
        `export const SEMANTIC_GOLDEN_PG${posture.serverMajor}: readonly string[] = Object.freeze([\n` +
        lines.map((l) => `  ${JSON.stringify(l)},`).join('\n') +
        `\n]);\n`;
      writeFileSync(file, body, 'utf8');
      console.log(`wrote ${lines.length} semantic posture lines to ${file} (sha256 ${posture.sha256}); add it to semantic-golden.ts if new.`);
      return;
    }
    if (!SEMANTIC_GOLDEN_BY_MAJOR[posture.serverMajor]) {
      console.error(`no semantic golden for PostgreSQL ${posture.serverMajor}`);
      process.exit(1);
    }
    const drifts = semanticDriftFromGolden(posture, existing);
    if (drifts.length) {
      console.error(`semantic posture DRIFT: ${describeSemanticDrift(drifts, 200)}`);
      process.exit(1);
    }
    console.log(`semantic posture matches the golden (PostgreSQL ${posture.serverMajor}, ${posture.core.length} core lines, ${posture.workspaces.size} workspace schema(s)).`);
  } finally {
    await client.end().catch(() => undefined);
  }
}

main().catch((error: Error) => {
  console.error(`semantic posture check failed: ${error.message.replace(/postgres(ql)?:\/\/\S+/g, '<url>')}`);
  process.exit(2);
});
